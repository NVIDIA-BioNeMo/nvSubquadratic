r"""TriHyena: Hyena operator over the rows or columns of a pair representation.

Background
----------
AlphaFold-style trunks update a pair representation :math:`z \in R^{B \times L
\times L \times C}` with triangle attention around the starting node (every row
attends over itself) and around the ending node (every column).  Both cost
:math:`O(L^3)`.  TriHyena ("Triangles Are All You Need: Subcubic Protein
Structure Prediction with TriHyena") replaces each of them with a 1D Hyena
operator run along the same axis, which is :math:`O(L^2 \log L)` in time and
memory while preserving the row / column structure.

Computation (starting node)
---------------------------
For every batch element and row :math:`i`, with projections
:math:`x_1, x_2, v` of the pair tensor (``query``, ``value``, ``key`` below):

.. math::

    \tilde{x}_1[i, j] &= \mathrm{CausalConv}_j(x_1)[i, j] \\
    \tilde{x}_2[i, j] &= \mathrm{CausalConv}_j(x_2)[i, j] \\
    \tilde{v}[i, j]   &= \mathrm{CausalConv}_i(v)[j, i]   \quad\text{(a column of } v \text{)} \\
    u[i, j]           &= \tilde{x}_1[i, j] \odot \tilde{v}[i, j] \\
    y[i, j]           &= \tilde{x}_2[i, j] \odot \sum_k h[j - k] \, u[i, k]

The long filter :math:`h` has :math:`2L - 1` taps and is generated by a SIREN
kernel network inside :class:`~nvsubquadratic.modules.ckconv_nd.CKConvND`; its
``mask_cfg`` limits the support (``BoxModulationND`` for a hard crop at
``|j - k| > max_offset``, ``GaussianModulationND`` / ``ExponentialModulationND``
for a soft learnable window).  The ending-node variant applies the same operator
to the transposed pair tensor and transposes the result back.

Layout
------
Reshaped to ``[B * L, L, C]`` every row is an ordinary 1D sequence.  The module
stays channel-last up to the long convolution: the depthwise causal short conv runs on the channel-last
tensors (``short_conv_backend="subq_ops"`` uses the NWH CUDA kernel) and the
only layout copy is the transpose into the long conv.  ``QKVSequenceMixer``
hands over its fused ``[B, L, L, 3C]`` projection un-split (``takes_fused_qkv``),
so in eager mode the starting node convolves the full ``3C``-wide stream straight
from the projection output (the key block of that call is unused) instead of
de-interleaving copies, at the cost of one extra ``[B * L, L, C]`` buffer.  Under
``torch.compile`` the short conv is instead written as shifted
multiply-adds (``_StencilConv``, either backend), which inductor fuses with the
projection slices, the padding mask, the gate and the transpose into the long
conv; nothing is copied in front of it.  The input projections
(``C -> 3C``) and the output projection live in
:class:`~nvsubquadratic.modules.sequence_mixer.QKVSequenceMixer`, and the
pre-norm in the surrounding residual block, as for every other mixer.

Example configuration
---------------------

.. code-block:: python

    LazyConfig(QKVSequenceMixer)(
        hidden_dim=C, out_proj_bias=True,
        mixer_cfg=LazyConfig(TriangleHyena)(
            hidden_dim=C,
            start_node=True,
            short_conv_backend="subq_ops",  # "torch" on CPU
            global_conv_cfg=LazyConfig(CKConvND)(
                data_dim=1, hidden_dim=C,
                kernel_cfg=LazyConfig(SIRENKernelND)(
                    out_dim=C, data_dim=1, mlp_hidden_dim=32, num_layers=3, embedding_dim=32,
                    omega_0=30.0, L_cache=L, use_bias=True,
                ),
                mask_cfg=LazyConfig(BoxModulationND)(data_dim=1, max_offset=256),  # hard window
                # mask_cfg=LazyConfig(GaussianModulationND)(data_dim=1, num_channels=C),  # soft window
                grid_type="double", fft_padding="zero", is_causal=False, use_shortcut=False,
                fft_backend="subq_ops",  # explicit_conv1d / fft_conv1d on GPU; "torch_fft" on CPU
            ),
        ),
    )

Related modules
---------------
* :mod:`nvsubquadratic.modules.hyena_nd` — the general ND Hyena operator this mirrors per row
* :mod:`nvsubquadratic.modules.ckconv_nd` — the long convolution and its mask
* :mod:`nvsubquadratic.modules.masks_nd` — hard (``BoxModulationND``) and soft windows
"""

import math
from collections.abc import Mapping
from typing import Literal

import torch
import torch.nn.functional as F

from nvsubquadratic.lazy_config import LazyConfig, instantiate
from nvsubquadratic.modules.sequence_mixer import QKVSequenceMixer
from nvsubquadratic.ops.causal_conv1d_custom import causal_conv1d


def _shifted_taps(x: torch.Tensor, weight: torch.Tensor, causal: bool) -> torch.Tensor:
    """Sum of ``weight[k] * x`` shifted by ``k`` taps along axis 1 of ``[N, L, C]`` (causal or anti-causal)."""
    taps, length = weight.shape[0], x.shape[1]
    padded = F.pad(x, (0, 0, taps - 1, 0) if causal else (0, 0, 0, taps - 1))
    shift = (lambda tap: tap) if causal else (lambda tap: taps - 1 - tap)
    return sum(weight[tap] * padded[:, shift(tap) : shift(tap) + length] for tap in range(taps))


class _StencilConv(torch.autograd.Function):
    """Depthwise causal short conv as shifted multiply-adds, for inductor to fuse with its neighbours."""

    @staticmethod
    def forward(ctx, x: torch.Tensor, weight: torch.Tensor) -> torch.Tensor:
        """Causal depthwise conv of ``x`` ``[N, L, C]`` with ``weight`` ``[K, C]``."""
        ctx.save_for_backward(x, weight)
        return _shifted_taps(x, weight, causal=True)

    @staticmethod
    def backward(ctx, grad: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        """Gradients with respect to ``x`` and ``weight``."""
        x, weight = ctx.saved_tensors
        taps, length = weight.shape[0], x.shape[1]
        padded = F.pad(x, (0, 0, taps - 1, 0))
        grad_weight = torch.stack([(grad * padded[:, tap : tap + length]).sum((0, 1)) for tap in range(taps)])
        return _shifted_taps(grad, weight, causal=False), grad_weight.to(weight.dtype)


class TriangleHyena(torch.nn.Module):
    """Starting- or ending-node Hyena mixer for pair tensors ``[B, L, L, C]``.

    Inner mixer for :class:`~nvsubquadratic.modules.sequence_mixer.QKVSequenceMixer`.
    It sets ``takes_fused_qkv`` so the mixer hands it the un-split ``[B, L, L, 3C]``
    projection; ``forward(q, k, v, ...)`` with three tensors works as well.

    Attributes:
        global_conv (torch.nn.Module): The 1D :class:`~nvsubquadratic.modules.ckconv_nd.CKConvND`
            long convolution (SIREN filter, window, FFT / Toeplitz backend).
        short_conv_weight (torch.nn.Parameter): Depthwise causal taps ``[K, 3C]`` for the
            ``query``, ``key`` and ``value`` streams, in that channel order.
        start_node (bool): ``True`` for the starting-node update (rows are the
            sequences), ``False`` for the ending-node update (columns).
    """

    #: Opts in to the un-split ``[B, L, L, 3C]`` projection from
    #: :class:`~nvsubquadratic.modules.sequence_mixer.QKVSequenceMixer`.
    takes_fused_qkv = True

    def __init__(
        self,
        hidden_dim: int,
        global_conv_cfg: LazyConfig,
        short_conv_kernel_size: int = 3,
        short_conv_backend: Literal["torch", "subq_ops"] = "torch",
        start_node: bool = True,
    ):
        """Build the short-conv taps and instantiate the long convolution.

        Args:
            hidden_dim: Channel width ``C`` of the pair tensor and of each projection.
            global_conv_cfg: :class:`~nvsubquadratic.lazy_config.LazyConfig` for a 1D
                non-causal :class:`~nvsubquadratic.modules.ckconv_nd.CKConvND` with
                ``hidden_dim`` channels (see the module docstring).
            short_conv_kernel_size: Taps of the depthwise causal short conv.
            short_conv_backend: ``"torch"`` runs the short conv with ``F.conv1d``;
                ``"subq_ops"`` with the channel-last ``subquadratic_ops_torch.causal_conv1d``
                CUDA kernel.  Under ``torch.compile`` both use the fused stencil form.
            start_node: ``True`` mixes along rows (starting node), ``False`` along
                columns (ending node).

        Raises:
            ValueError: If ``short_conv_backend`` is not ``"torch"`` or ``"subq_ops"``, or
                ``global_conv_cfg`` is not a 1D non-causal zero-padded double-grid ``CKConvND``
                with ``hidden_dim`` channels, or its kernel is FiLM-conditioned.
        """
        super().__init__()
        if short_conv_backend not in ("torch", "subq_ops"):
            raise ValueError(f"short_conv_backend must be 'torch' or 'subq_ops', got {short_conv_backend!r}")
        self.hidden_dim = hidden_dim
        self.start_node = start_node
        self.short_conv_backend = short_conv_backend
        self.global_conv = instantiate(global_conv_cfg)
        conv = self.global_conv
        if (
            conv.data_dim != 1
            or conv.is_causal
            or conv.hidden_dim != hidden_dim
            or conv.grid_type == "single"
            or any(conv._periodic_per_axis)
        ):
            raise ValueError(
                f"global_conv must be a 1D non-causal zero-padded double-grid CKConvND with hidden_dim={hidden_dim}, "
                f"got data_dim={conv.data_dim}, is_causal={conv.is_causal}, hidden_dim={conv.hidden_dim}, "
                f"grid_type={conv.grid_type!r}, fft_padding={conv.fft_padding!r}"
            )
        if getattr(conv.kernel, "film_generator", None) is not None:
            raise ValueError("TriangleHyena does not support FiLM kernels: conditioning cannot reach the long conv.")
        weight = torch.empty(3 * hidden_dim, short_conv_kernel_size)
        torch.nn.init.kaiming_uniform_(weight, a=math.sqrt(5))
        self.short_conv_weight = torch.nn.Parameter(weight.t().contiguous())

    def extra_repr(self) -> str:
        """Return a short summary string."""
        return (
            f"hidden_dim={self.hidden_dim}, start_node={self.start_node}, "
            f"short_conv_kernel_size={self.short_conv_weight.shape[0]}, short_conv_backend={self.short_conv_backend!r}"
        )

    def flop_count(self, spatial_dims: tuple[int, int], inference: bool = False) -> int:
        """Count FLOPs for one forward pass over an ``L x L`` pair tensor.

        Short conv (three depthwise streams), the two gates, and the long conv
        once per row; the SIREN filter and its FFT run once per forward, so
        their cost is counted once.

        Args:
            spatial_dims: ``(L, L)``.
            inference: Forwarded to ``global_conv.flop_count``.

        Returns:
            Total FLOP count; a multiply-add counts as 2 FLOPs, as in
            :meth:`QKVSequenceMixer.flop_count`.
        """
        seq_len = spatial_dims[0]
        positions = seq_len * seq_len
        flops = 2 * 3 * self.hidden_dim * self.short_conv_weight.shape[0] * positions
        flops += 2 * self.hidden_dim * positions
        # SIREN and filter FFT run once per forward; per-row terms scale with seq_len
        per_row = self.global_conv.flop_count((seq_len,), inference=True)
        flops += (seq_len - 1) * per_row + self.global_conv.flop_count((seq_len,), inference=inference)
        return flops

    def _short_conv(self, x: torch.Tensor, weight: torch.Tensor) -> torch.Tensor:
        """Depthwise causal conv along the sequence axis of channel-last ``x`` ``[N, L, C]``, taps ``[K, C]``."""
        weight = weight.to(x.dtype)
        taps = weight.shape[0]
        if torch.compiler.is_compiling():
            return _StencilConv.apply(x, weight)
        if self.short_conv_backend == "subq_ops":
            return causal_conv1d(x.contiguous(), weight.contiguous(), None, "identity", channel_last=True)
        y = F.conv1d(F.pad(x.transpose(1, 2), (taps - 1, 0)), weight.t().unsqueeze(1), groups=weight.shape[1])
        return y.transpose(1, 2)

    def _stream_weight(self, stream: int) -> torch.Tensor:
        """Taps ``[K, C]`` of one of the three channel blocks."""
        return self.short_conv_weight[:, stream * self.hidden_dim : (stream + 1) * self.hidden_dim]

    def forward(
        self,
        query: torch.Tensor,
        key: torch.Tensor | None = None,
        value: torch.Tensor | None = None,
        cp_group: torch.distributed.ProcessGroup = None,
        padding_mask: torch.Tensor | None = None,
        **mixer_kwargs,
    ) -> torch.Tensor:
        """Apply the row- or column-wise Hyena update.

        Args:
            query: ``[B, L, L, C]`` gate-input projection (reference ``x1``), or, when ``key``
                and ``value`` are ``None``, the fused ``[B, L, L, 3C]`` projection
                ``[query | key | value]`` as :class:`~nvsubquadratic.modules.sequence_mixer.QKVSequenceMixer`
                passes it (``takes_fused_qkv``).
            key: ``[B, L, L, C]`` projection whose columns feed the long conv (reference ``v``).
            value: ``[B, L, L, C]`` output-gate projection (reference ``x2``).
            cp_group: Context-parallel group; only ``None`` or a group of size 1 is supported.
            padding_mask: Optional ``[B, L]`` boolean tensor, ``True`` at padded tokens.  The
                projections are zeroed at every pair position in a padded row or column before
                the short conv, and the long-conv input and output gate again after it.
            **mixer_kwargs: Only ``conditioning`` is accepted, and it is ignored (no FiLM kernel
                conditioning).

        Returns:
            ``[B, L, L, C]`` update of the pair tensor.

        Raises:
            ValueError: If the pair tensor is not square, the channel width does not match
                ``hidden_dim``, only one of ``key`` / ``value`` is given, or ``cp_group`` has size > 1.
            TypeError: If ``mixer_kwargs`` holds any key other than ``conditioning``.
        """
        if cp_group is not None and cp_group.size() > 1:
            raise ValueError("TriangleHyena does not support context parallelism.")
        mixer_kwargs.pop("conditioning", None)  # AdaLN-zero blocks always pass conditioning
        if mixer_kwargs:
            raise TypeError(f"TriangleHyena got unexpected mixer kwargs {sorted(mixer_kwargs)}.")
        if (key is None) != (value is None):
            raise ValueError("TriangleHyena takes either (query, key, value) or the fused qkv tensor alone.")
        qkv = query if key is None else torch.cat([query, key, value], dim=-1)
        batch, rows, cols, width = qkv.shape
        channels = self.hidden_dim
        if rows != cols or width != 3 * channels:
            raise ValueError(
                f"TriangleHyena needs a square pair tensor [B, L, L, 3C] with C={channels}, got {tuple(qkv.shape)}."
            )
        flat = (batch * rows, rows, channels)
        if padding_mask is not None:
            # Zero padded pairs before the short conv so padded values never reach valid ones.
            pair_mask = (padding_mask[:, :, None] | padding_mask[:, None, :])[..., None]
            qkv = qkv.masked_fill(pair_mask, 0)
        key = qkv[..., channels : 2 * channels]
        row_in, col_in = (qkv, key.transpose(1, 2)) if self.start_node else (qkv.transpose(1, 2), key)
        if self.start_node and not torch.compiler.is_compiling():
            rows_out = self._short_conv(row_in.reshape(batch * rows, rows, 3 * channels), self.short_conv_weight)
            x1, x2 = rows_out[..., :channels], rows_out[..., 2 * channels :]
        else:
            x1 = self._short_conv(row_in[..., :channels].reshape(flat), self._stream_weight(0))
            x2 = self._short_conv(row_in[..., 2 * channels :].reshape(flat), self._stream_weight(2))
        v = self._short_conv(col_in.reshape(flat), self._stream_weight(1))
        if padding_mask is not None:
            mask = pair_mask.reshape(batch * rows, rows, 1)
            x1 = x1.masked_fill(mask, 0)
            x2 = x2.masked_fill(mask, 0)
        z = (x1 * v).transpose(1, 2).contiguous()
        y = x2 * self.global_conv(z, is_bhl_input=True).transpose(1, 2)
        y = y.reshape(batch, rows, rows, channels)
        return y if self.start_node else y.transpose(1, 2)


def load_reference_state_dict(
    mixer: QKVSequenceMixer, state_dict: Mapping[str, torch.Tensor]
) -> dict[str, torch.Tensor]:
    """Load a reference TriHyena checkpoint into ``QKVSequenceMixer(TriangleHyena)``.

    The original TriHyena ``TriangleHyena`` module stores ``linear_x12i``
    (``x1`` and ``x2`` stacked), ``linear_vj``, a ``(3D, 3)`` causal short-conv
    weight over ``[x1 | x2 | v]``, ``siren_kernel.*``, ``to_out`` and a pre-norm.
    This maps them onto ``qkv_proj`` (``[x1 | v | x2]`` channel blocks),
    ``short_conv_weight`` (same remap, transposed to ``[3, 3D]``), ``global_conv.kernel``
    and ``out_proj``, and zeroes ``qkv_proj.bias`` and ``global_conv.shortcut`` when
    the mixer has them (the reference has neither; build with ``qkv_bias=False`` and
    ``use_shortcut=False`` to drop them).

    The mixer must be built to match: ``SIRENKernelND(L_cache=2 * L - 1)`` with the
    reference ``L`` (its SIREN grid spans ``[-0.5, 0.5]``), ``mask_cfg =
    BoxModulationND(max_offset=<reference max_offset>)`` or ``Identity`` when it was
    ``0``, ``short_conv_kernel_size=3`` and ``out_proj_bias=True``.

    Args:
        mixer: ``QKVSequenceMixer`` whose ``mixer`` is a :class:`TriangleHyena`.
        state_dict: Reference state dict, optionally prefixed with ``core.``.

    Returns:
        The reference pre-norm tensors (``weight``, ``bias``) for the caller to
        load into the residual block's ``LayerNorm``.

    Raises:
        ValueError: If a tensor's shape does not match the mixer's, or a reference key is missing.
    """
    ref = {key.removeprefix("core."): value for key, value in state_dict.items()}
    kernel = mixer.mixer.global_conv.kernel
    width = mixer.qkv_proj.out_features // 3
    try:
        norm = {"weight": ref["norm.weight"], "bias": ref["norm.bias"]}
        x12 = ref["linear_x12i.weight"]
        w_x1, w_x2, w_v = ref["W_conv_x12i_vj"].split(width)
        target = {
            "qkv_proj.weight": torch.cat([x12[:width], ref["linear_vj.weight"], x12[width:]]),
            "out_proj.weight": ref["to_out.weight"],
            "out_proj.bias": ref["to_out.bias"],
            "mixer.short_conv_weight": torch.cat([w_x1, w_v, w_x2]).t().contiguous(),
            "mixer.global_conv.kernel.positional_embedding.linear.weight": ref[
                "siren_kernel.positional_embedding.linear.weight"
            ],
            "mixer.global_conv.kernel.positional_embedding.linear.bias": ref[
                "siren_kernel.positional_embedding.linear.bias"
            ],
            "mixer.global_conv.kernel.out_linear.weight": ref["siren_kernel.out_linear.weight"],
            "mixer.global_conv.kernel.out_linear.bias": ref["siren_kernel.out_linear.bias"],
        }
        for index in range(len(kernel.hidden_linears)):
            for name in ("weight", "bias"):
                target[f"mixer.global_conv.kernel.hidden_linears.{index}.{name}"] = ref[
                    f"siren_kernel.kernel_network.{2 * index}.{name}"
                ]
    except KeyError as exc:
        raise ValueError(f"reference state dict lacks {exc}") from exc
    if f"siren_kernel.kernel_network.{2 * len(kernel.hidden_linears)}.weight" in ref:
        raise ValueError(f"reference SIREN has more than the mixer's {len(kernel.hidden_linears)} hidden layers")
    current = mixer.state_dict()
    for name, tensor in target.items():
        if name not in current:
            raise ValueError(f"mixer has no parameter {name!r}; build it as documented in load_reference_state_dict")
        if current[name].shape != tensor.shape:
            raise ValueError(f"{name}: mixer shape {tuple(current[name].shape)} != reference {tuple(tensor.shape)}")
    for name in ("qkv_proj.bias", "mixer.global_conv.shortcut"):
        if name in current:
            target[name] = torch.zeros_like(current[name])
    mixer.load_state_dict({**current, **target})
    return norm
